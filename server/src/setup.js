import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import readline from 'readline';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.resolve(__dirname, '../.env');

if (fs.existsSync(envPath)) {
  console.log('✓ server/.env already exists. Leaving untouched.');
  process.exit(0);
}

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
});

function ask(question, defaultValue = '') {
  return new Promise(resolve => {
    rl.question(question, answer => {
      resolve(answer.trim() || defaultValue);
    });
  });
}

async function run() {
  console.log('\n--- Nexus ERP Setup ---\n');
  const defaultUri = 'mongodb://localhost:27017/nexus-erp';
  const uri = await ask(`MongoDB URI [default: ${defaultUri}]: `, defaultUri);
  const jwtSecret = crypto.randomBytes(32).toString('hex');
  const clientOrigin = 'http://localhost:5173';
  const port = '4000';

  const content = `# Generated by npm run setup
MONGODB_URI=${uri}
JWT_SECRET=${jwtSecret}
CLIENT_ORIGIN=${clientOrigin}
PORT=${port}
`;

  fs.writeFileSync(envPath, content, 'utf8');
  console.log('✓ server/.env created successfully with secure JWT secret.');
  rl.close();
}

run().catch(err => {
  console.error('Setup failed:', err);
  process.exit(1);
});
